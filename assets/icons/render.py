"""Render the icon SVGs to PNGs with Chromium (Playwright). Run from the repo root:
   .venv/bin/python assets/icons/render.py
"""
from pathlib import Path

from playwright.sync_api import sync_playwright

HERE = Path(__file__).parent
JOBS = [  # (svg, size, png)
    ("icon-ghost-small.svg", 32, "ghost-32.png"),
    ("icon-ghost-small.svg", 64, "ghost-64.png"),
    ("icon-ghost-apple.svg", 180, "ghost-180.png"),           # apple-touch-icon: full-bleed, iOS only rounds corners
    ("icon-ghost.svg", 192, "ghost-192.png"),                 # manifest purpose "any"
    ("icon-ghost.svg", 512, "ghost-512.png"),
    ("icon-ghost-maskable.svg", 192, "ghost-maskable-192.png"),  # manifest purpose "maskable"
    ("icon-ghost-maskable.svg", 512, "ghost-maskable-512.png"),
]

def make_fullbleed(scale: float, name: str, label: str) -> None:
    """Derive a full-bleed icon from the main one: square background, artwork shrunk by `scale`.
    maskable (Android, any mask shape): 0.72 keeps everything inside the 80 % safe circle.
    apple (iOS only rounds the corners): 0.86 keeps it big but clear of the rounded corners."""
    src = (HERE / "icon-ghost.svg").read_text()
    tile = '<rect width="512" height="512" rx="112" fill="url(#bg)"/>'
    assert tile in src, "main icon's tile rect changed - update make_maskable()"
    out = src.replace(tile, '<rect width="512" height="512" fill="url(#bg)"/>\n'
                            f'  <g transform="translate(256 256) scale({scale}) translate(-256 -256)">', 1)
    out = out.replace("</svg>", "  </g>\n</svg>")
    out = out.replace("Ghost train, full detail.", f"GENERATED by render.py from icon-ghost.svg ({label}).", 1)
    (HERE / name).write_text(out)


make_fullbleed(0.72, "icon-ghost-maskable.svg", "maskable")
make_fullbleed(0.86, "icon-ghost-apple.svg", "apple-touch")
with sync_playwright() as p:
    b = p.chromium.launch()
    for svg, size, png in JOBS:
        pg = b.new_page(viewport={"width": size, "height": size}, device_scale_factor=1)
        markup = (HERE / svg).read_text()
        pg.set_content(f"<html><body style='margin:0;background:transparent'>"
                       f"<div style='width:{size}px;height:{size}px'>{markup}</div></body></html>")
        pg.evaluate("s => { const e = document.querySelector('svg'); e.setAttribute('width', s); e.setAttribute('height', s); }", size)
        pg.locator("svg").screenshot(path=str(HERE / png), omit_background=True)
        pg.close()
        print(f"{png:24} <- {svg} @ {size}px")
    b.close()
